import { createPublicClient, createWalletClient, http } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { arbitrumSepolia } from "viem/chains";
import { createCofheClient, createCofheConfig } from "@cofhe/sdk/node";
import { Encryptable, FheTypes } from "@cofhe/sdk";
import { arbSepolia } from "@cofhe/sdk/chains";
import fs from "fs";
const abi = JSON.parse(fs.readFileSync("../artifacts/contracts/UnravixProof.sol/UnravixProof.json")).abi;
const address = "0xBBe53FFd63b9A718eF02c0A509457EE264431e43";
const account = privateKeyToAccount(process.env.PRIVATE_KEY);
const transport = http("https://sepolia-rollup.arbitrum.io/rpc");
const pc = createPublicClient({ chain: arbitrumSepolia, transport });
const wc = createWalletClient({ chain: arbitrumSepolia, transport, account });
const client = createCofheClient(createCofheConfig({ supportedChains: [arbSepolia] }));
await client.connect(pc, wc);
console.log("connected");
const T=()=>((Date.now()-t0)/1000).toFixed(1)+"s"; let t0=Date.now();
const k = await client.encryptInputs([2n,0n,3n].map(x=>Encryptable.uint8(x))).setConsumingContract(address).execute();
console.log("encrypted key", T());
let h = await wc.writeContract({ address, abi, functionName: "createQuiz", args: ["Demo: limits", 2, k.slice(0,-1), k[k.length-1]] });
let r = await pc.waitForTransactionReceipt({ hash: h }); console.log("createQuiz", h, r.status, "gas", r.gasUsed, T());
const id = await pc.readContract({ address, abi, functionName: "quizCount" });
t0=Date.now();
const a = await client.encryptInputs([2n,0n,1n].map(x=>Encryptable.uint8(x))).setConsumingContract(address).execute();
h = await wc.writeContract({ address, abi, functionName: "submit", args: [id, a.slice(0,-1), a[a.length-1]] });
r = await pc.waitForTransactionReceipt({ hash: h }); console.log("submit", h, r.status, "gas", r.gasUsed, T());
await client.acp.createSelf({ issuer: account.address });
t0=Date.now();
const sh = await pc.readContract({ address, abi, functionName: "myScore", args: [id], account: account.address });
for (let i=0;i<20;i++){ try { const sc = await client.decryptForView(sh, FheTypes.Uint8).execute(); console.log("SCORE", sc.toString(), "expected 2", T()); break; } catch(e){ if(i==19) console.log("decrypt fail", String(e.message).slice(0,300)); await new Promise(r=>setTimeout(r,6000)); } }
process.exit(0);
